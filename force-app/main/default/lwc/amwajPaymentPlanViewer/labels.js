export const isArabic = (LANG || '').toLowerCase().startsWith('ar');
const ACTIVE = isArabic ? DICT.ar : DICT.en;

/** t('key') → chrome string; t('key', value) replaces {0}. */
export function t(key, value) {
    let s = ACTIVE[key] !== undefined ? ACTIVE[key] : DICT.en[key] || key;
    if (value !== undefined && value !== null) {
        s = s.replace('{0}', String(value));
    }
    return s;
}